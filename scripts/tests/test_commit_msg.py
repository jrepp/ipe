"""Regression tests for the commit-message hook."""

import subprocess
import tempfile
import unittest
from pathlib import Path


HOOK = Path(__file__).resolve().parents[1] / "check-commit-msg"


class CommitMessageTests(unittest.TestCase):
    def check_message(self, message, accepted):
        with tempfile.TemporaryDirectory() as directory:
            message_file = Path(directory) / "COMMIT_EDITMSG"
            message_file.write_text(message, encoding="utf-8")
            result = subprocess.run(
                [str(HOOK), str(message_file)], capture_output=True, text=True
            )
        self.assertEqual(result.returncode, 0 if accepted else 1, result.stderr)

    def test_conventional_subjects(self):
        for message in (
            "fix: reject malformed input\n",
            "feat(api): add discovery\n\nBound requests to the configured limit.\n",
            "refactor(core)!: replace storage interface\n",
            "docs: describe café configuration\n",
        ):
            with self.subTest(message=message):
                self.check_message(message, True)

    def test_invalid_subjects(self):
        for message in ("", "update files\n", "unknown: update files\n", "fix: \n"):
            with self.subTest(message=message):
                self.check_message(message, False)

    def test_rejects_emoji_in_subject_and_body(self):
        for emoji in ("\U0001f680", "\u2705"):
            for message in (
                f"fix: repair input {emoji}\n",
                f"fix: repair input\n\nDetails {emoji}\n",
            ):
                with self.subTest(message=message):
                    self.check_message(message, False)

    def test_rejects_attribution_in_body(self):
        self.check_message(
            "fix: repair input\n\nCo-Authored-By: Example <a@example.com>\n", False
        )
        self.check_message("fix: repair input\n\nGenerated by a tool\n", False)


if __name__ == "__main__":
    unittest.main()
