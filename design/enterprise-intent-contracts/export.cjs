// Build the shareable page from the repository source and shared site styles.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const source = process.argv[2] || 'index.html';
const output = process.argv[3] || 'enterprise-intent-contracts.html';
let html = fs.readFileSync(path.join(root, source), 'utf8');
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, relative) => {
  const file = path.resolve(root, relative);
  let css = fs.readFileSync(file, 'utf8');
  css = css.replace(/url\(["']?([^"')]+)["']?\)/g, (_, asset) => {
    if (asset.startsWith('data:') || asset.startsWith('#')) return `url("${asset}")`;
    const data = fs.readFileSync(path.resolve(path.dirname(file), asset));
    if (!asset.endsWith('.woff2')) throw new Error(`Unsupported CSS asset: ${asset}`);
    return `url("data:font/woff2;base64,${data.toString('base64')}")`;
  });
  return `<style>\n${css}\n</style>`;
});
// Inline scripts run after the markup, preserving deferred-script order.
const scripts = [];
html = html.replace(/<script src="([^"]+)" defer><\/script>/g, (_, relative) => {
  scripts.push(fs.readFileSync(path.resolve(root, relative), 'utf8').replace(/<\/script/gi, '<\\/script'));
  return '';
});
html = html.replace(/<a href="(?!#|https?:\/\/)[^"]*">([\s\S]*?)<\/a>/g, '$1');
const notices = [
  fs.readFileSync(path.join(root, 'vendor/D3-LICENSE'), 'utf8'),
  fs.readFileSync(path.resolve(root, '../../tools/product-ship-mocks/fonts/LICENSE.txt'), 'utf8'),
].join('\n\n').replace(/--/g, '—');
html = html.replace('</body>', () => scripts.map(source => `<script>\n${source}\n</script>`).join('\n') + '\n</body>');
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by export.cjs. Edit the source files and rebuild. -->');
html += `\n<!-- Bundled dependency licenses\n${notices}\n-->\n`;
const destination = path.join(root, output);
// Remove indentation left by inlined script tags.
html = html.replace(/^[ \t]+$/gm, '');
fs.writeFileSync(destination, html);
console.log(`Saved ${path.basename(destination)} (${Math.ceil(Buffer.byteLength(html) / 1024)} KiB). No companion files required.`);
